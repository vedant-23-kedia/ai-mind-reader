"""Phase 6: turn recorded games into measured per-attribute error rates.

Reads the feedback log the app writes, and produces:

  data/noise_profile.json           measured error rate per attribute, which
                                    the engine loads instead of assuming one
                                    global constant
  data/new_object_candidates.json   objects players named that the dataset
                                    does not have, with a draft attribute
                                    list assembled from their answers

Nothing is applied to the dataset automatically. A draft built from a handful
of strangers' answers is a proposal for review, not ground truth.

Run:  .venv/Scripts/python scripts/learn_from_feedback.py
      .venv/Scripts/python scripts/learn_from_feedback.py --log <path>
      .venv/Scripts/python scripts/learn_from_feedback.py --evaluate
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from mindreader import config as cfg  # noqa: E402
from mindreader.dataset import load_prototypes  # noqa: E402
from mindreader.engine import DEFAULT_NOISE  # noqa: E402
from mindreader.feedback import (  # noqa: E402
    estimate_attribute_noise,
    load_feedback,
    new_object_candidates,
    write_noise_profile,
)

NOISE_PROFILE = cfg.DATA_DIR / "noise_profile.json"
CANDIDATES = cfg.DATA_DIR / "new_object_candidates.json"
SAMPLE_LOG = cfg.DATA_DIR / "sample_feedback_log.csv"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--log", type=Path, default=None,
                    help="feedback log to read (default: the app's own log, "
                         "falling back to the committed sample)")
    ap.add_argument("--min-observations", type=int, default=5,
                    help="only report attributes with at least this many "
                         "observations (default 5)")
    ap.add_argument("--evaluate", action="store_true",
                    help="also measure whether the learned profile improves "
                         "accuracy against simulated players")
    args = ap.parse_args()

    log_path = args.log
    if log_path is None:
        log_path = cfg.FEEDBACK_LOG if cfg.FEEDBACK_LOG.exists() else SAMPLE_LOG

    protos = load_prototypes()
    rows = load_feedback(log_path)

    print("=" * 76)
    print("PHASE 6: LEARNING FROM RECORDED GAMES")
    print("=" * 76)
    print("  log: %s" % log_path)
    if log_path == SAMPLE_LOG:
        print("  NOTE: this is the committed SYNTHETIC sample, generated by")
        print("        scripts/make_sample_feedback.py. It demonstrates the")
        print("        mechanism; it is not real player data.")
    print("  %d usable rows" % len(rows))

    if not rows:
        print()
        print("  Nothing to learn from yet. The log fills up as players mark")
        print("  guesses wrong and say what they were thinking of.")
        return 0

    # ---- per-attribute noise ----------------------------------------------
    est = estimate_attribute_noise(rows, protos, default_rate=DEFAULT_NOISE)
    print()
    print("1. PER-ATTRIBUTE ERROR RATES")
    print("   %d rows named a known object and could be scored; %d named"
          % (est.rows_used, est.rows_skipped))
    print("   something not in the dataset and are handled in section 2.")
    print("   measured global error rate: %.1f%%  (the engine assumed %.1f%%)"
          % (est.global_rate * 100, DEFAULT_NOISE * 100))
    print()

    scored = [(f, est.per_attribute[f], est.observations[f], est.errors[f])
              for f in protos.features
              if est.observations[f] >= args.min_observations]
    scored.sort(key=lambda t: -t[1])
    if scored:
        print("   %-24s %8s %8s %8s" % ("attribute", "rate", "wrong", "asked"))
        print("   least reliably answered:")
        for f, rate, n, e in scored[:8]:
            print("     %-22s %7.1f%% %8d %8d" % (f, rate * 100, e, n))
        print("   most reliably answered:")
        for f, rate, n, e in scored[-5:][::-1]:
            print("     %-22s %7.1f%% %8d %8d" % (f, rate * 100, e, n))
    else:
        print("   (no attribute has %d+ observations yet; every estimate is"
              % args.min_observations)
        print("    still dominated by the smoothing prior)")

    write_noise_profile(est, NOISE_PROFILE)
    print()
    print("   wrote %s" % NOISE_PROFILE.relative_to(cfg.ROOT))
    print("   the app and engine pick this up automatically on next start")

    # ---- new object candidates --------------------------------------------
    cands = new_object_candidates(rows, protos)
    print()
    print("2. OBJECTS PLAYERS NAMED THAT THE DATASET DOES NOT HAVE")
    if not cands:
        print("   none")
    else:
        print("   %d candidate(s)" % len(cands))
        payload = []
        for c in cands[:12]:
            draft = c.draft_attributes()
            disputed = c.disputed()
            print("     %-20s %d report(s), %d attributes agreed%s"
                  % (c.name, c.reports, len(draft),
                     ", %d disputed" % len(disputed) if disputed else ""))
            payload.append({
                "name": c.name,
                "reports": c.reports,
                "draft_attributes": draft,
                "disputed_attributes": disputed,
                "votes": {k: {"yes": v[0], "no": v[1]}
                          for k, v in sorted(c.votes.items())},
            })
        CANDIDATES.write_text(json.dumps({
            "note": (
                "Draft entries for data/source/objects.json, assembled from "
                "players' own answers. REVIEW BEFORE USE: an attribute vector "
                "built from a few strangers' answers is a suggestion, and the "
                "separability gate in build_dataset.py must still pass "
                "afterwards."
            ),
            "candidates": payload,
        }, indent=2), encoding="utf-8")
        print()
        print("   wrote %s" % CANDIDATES.relative_to(cfg.ROOT))
        print("   these are drafts for review, not automatic additions")

    # ---- optional: does the learned profile actually help? ----------------
    if args.evaluate:
        from mindreader.evaluation import run_games, summarise

        print()
        print("3. DOES THE LEARNED PROFILE HELP?")
        print("   Simulated players here still use a uniform error rate, so")
        print("   this mostly checks the profile does no harm. Proving it")
        print("   helps needs players whose reliability genuinely varies by")
        print("   attribute - i.e. real ones.")
        vec = est.as_vector(protos.features)
        print()
        print("   %-28s %8s %9s" % ("engine noise model", "top1", "questions"))
        for label, noise in (("global %.0f%%" % (DEFAULT_NOISE * 100),
                              DEFAULT_NOISE),
                             ("learned per-attribute", vec)):
            res = run_games(protos, 0.10, 4, engine_noise=noise)
            s = summarise(res)
            print("   %-28s %7.1f%% %9.1f"
                  % (label, s["top1"], s["mean_questions"]))
        print()
        print("   learned rates span %.1f%% to %.1f%% (mean %.1f%%)"
              % (vec.min() * 100, vec.max() * 100, vec.mean() * 100))

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
